export function ideaToMarkdown(idea: SaasIdea, subreddit: string): string {
  const threads = idea.source_threads.length
    ? idea.source_threads.map((t) => `- [${t.title}](${t.thread_url})`).join("\n")
    : "- —";

  return [
    `# ${idea.idea_name}`,
    ``,
    `> **Source:** r/${subreddit} · **Score:** ${idea.score}/10 · **Verdict:** ${idea.verdict} · **Demand:** ${idea.demand_level}`,
    ``,
    `## Problem`,
    ``,
    idea.problem,
    ``,
    `## Opportunity`,
    ``,
    idea.opportunity,
    ``,
    `## User Complaints`,
    ``,
    ...idea.user_complaints.map((c) => `- ${c}`),
    ``,
    `## Existing Solutions`,
    ``,
    ...idea.existing_solutions.map((s) => `- ${s}`),
    ``,
    `## Similar Competitors`,
    ``,
    ...idea.similar_competitors.map((c) => `- ${c}`),
    ``,
    `## Monetization`,
    ``,
    idea.monetization_model,
    ``,
    `## Pricing Hint`,
    ``,
    idea.pricing_hint,
    ``,
    `## Revenue Potential`,
    ``,
    idea.revenue_potential,
    ``,
    `## Go to Market`,
    ``,
    idea.go_to_market,
    ``,
    `## Source Threads`,
    ``,
    threads,
    ``,
    `---`,
    `*Generated by [Validly](https://validly.dev)*`,
  ].join("\n");
}


export type ExportFormat = "text" | "markdown" | "json" | "image";

export async function exportIdea(
  idea: SaasIdea,
  subreddit: string,
  format: ExportFormat,
): Promise<void> {
  const name = slug(idea);
  const sub = subreddit.toLowerCase();

  if (format === "text") {
    downloadBlob(new Blob([ideaToText(idea, subreddit)], { type: "text/plain" }), `${name}-${sub}.txt`);
  } else if (format === "markdown") {
    downloadBlob(new Blob([ideaToMarkdown(idea, subreddit)], { type: "text/markdown" }), `${name}-${sub}.md`);
  } else if (format === "json") {
    downloadBlob(new Blob([ideaToJson(idea, subreddit)], { type: "application/json" }), `${name}-${sub}.json`);
  } else {
    const blob = await ideaToPng(idea, subreddit);
    downloadBlob(blob, `${name}-${sub}.png`);
  }
}

export async function exportAllIdeas(
  ideas: SaasIdea[],
  subreddit: string,
  format: ExportFormat,
): Promise<void> {
  const sub = subreddit.toLowerCase();
  const ts = new Date().toISOString().slice(0, 10);
  const base = `validly-${sub}-${ts}`;

  if (format === "text") {
    downloadBlob(new Blob([ideasToText(ideas, subreddit)], { type: "text/plain" }), `${base}.txt`);
  } else if (format === "markdown") {
    downloadBlob(new Blob([ideasToMarkdown(ideas, subreddit)], { type: "text/markdown" }), `${base}.md`);
  } else if (format === "json") {
    downloadBlob(new Blob([ideasToJson(ideas, subreddit)], { type: "application/json" }), `${base}.json`);
  } else {
    // Bulk image: download each card individually
    const blobs = await ideasToPng(ideas, subreddit);
    blobs.forEach((blob, i) => {
      const s = slug(ideas[i]);
      downloadBlob(blob, `${base}-${i + 1}-${s}.png`);
    });
  }
}
